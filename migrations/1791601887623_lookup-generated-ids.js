// The lookup module creates rows in these tables without an id, expecting the
// database to generate one (services/lookupTables.ts, `idGenerated: true`), but
// on prod their ids had no default, so every create was a 500. Give each an
// identity, started past the ids already there (seeded rows carry explicit ids).
// payment_period is closed to creates (ADR-0011) but gets the same default, so
// the description stays true.

const TABLES = ['agreement_duration', 'increment_duration', 'increment_percentage', 'payment_period'];

exports.up = (pgm) => {
  for (const table of TABLES) {
    pgm.sql(`
      ALTER TABLE public.${table} ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
      SELECT setval(
        pg_get_serial_sequence('public.${table}', 'id'),
        COALESCE((SELECT MAX(id) FROM public.${table}), 1),
        (SELECT MAX(id) FROM public.${table}) IS NOT NULL
      );
    `);
  }
};

